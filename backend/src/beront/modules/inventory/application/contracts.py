from dataclasses import dataclass
from decimal import Decimal
from typing import Protocol
from uuid import UUID

from beront.modules.inventory.domain.entities import Balance, Movement


@dataclass(frozen=True)
class StockRequirement:
    product_id: UUID
    variant_id: UUID
    kind: str
    volume_ml: Decimal
    quantity: int = 1


class StockRepository(Protocol):
    def ensure_decants(self, product_id: UUID) -> None: ...
    def ensure_bottles(self, variant_id: UUID) -> None: ...
    def amounts(self, kind: str, target_ids: list[UUID]) -> dict[UUID, Decimal]: ...
    def balance(self, kind: str, target_id: UUID, *, lock=False) -> Balance: ...
    def save_balance(self, balance: Balance) -> None: ...
    def movement(self, operation_id: UUID) -> Movement | None: ...
    def add_movement(self, movement: Movement, balance_id: UUID) -> None: ...
    def balances(self, page: int, page_size: int) -> tuple[list[Balance], int]: ...
    def movements(self, page: int, page_size: int) -> tuple[list[Movement], int]: ...
