from typing import Protocol
from uuid import UUID


class CommerceRepository(Protocol):
    def settings(self) -> dict | None: ...
    def save_settings(self, data: dict) -> dict: ...
    def listing(self, resource: str, *, private=False) -> list[dict]: ...
    def get(self, resource: str, identifier: UUID) -> dict: ...
    def add(self, resource: str, data: dict) -> dict: ...
    def save(self, resource: str, data: dict) -> dict: ...
    def destination(self, city_id: UUID) -> dict: ...
