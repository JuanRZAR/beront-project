from typing import BinaryIO, Protocol
from uuid import UUID

from beront.modules.catalog.domain.entities import Brand, Product, ProductImage, Variant


class CatalogRepository(Protocol):
    def definitions(self, resource: str, *, private=False) -> list[dict]: ...
    def definition(self, resource: str, identifier: UUID) -> dict: ...
    def add_definition(self, resource: str, values: dict) -> dict: ...
    def set_options(self, product_id: UUID, resource: str, slugs: list[str]) -> None: ...
    def save_definition(self, resource: str, values: dict) -> dict: ...
    def product(self, product_id: UUID, *, lock=False) -> Product: ...
    def by_slug(self, slug: str) -> Product: ...
    def candidates(self, filters: dict, *, private=False, offset=0, limit=100) -> list[Product]: ...
    def add_product(self, product: Product) -> None: ...
    def save_product(self, product: Product) -> None: ...
    def add_variant(self, variant: Variant) -> None: ...
    def save_variant(self, variant: Variant) -> None: ...
    def variant(self, variant_id: UUID) -> Variant: ...
    def brands(self, *, private=False) -> list[Brand]: ...
    def brand(self, brand_id: UUID) -> Brand: ...
    def add_brand(self, brand: Brand) -> None: ...
    def save_brand(self, brand: Brand) -> None: ...
    def add_image(self, image: ProductImage) -> None: ...
    def image(self, image_id: UUID) -> ProductImage: ...
    def image_by_filename(self, filename: str) -> ProductImage: ...
    def save_image(self, image: ProductImage) -> None: ...
    def delete_image(self, image_id: UUID, version: int) -> None: ...


class ImageStorage(Protocol):
    def save(self, stream: BinaryIO) -> str: ...
    def delete(self, filename: str) -> None: ...
