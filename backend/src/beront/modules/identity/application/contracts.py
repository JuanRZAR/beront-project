from typing import Protocol

from beront.modules.identity.domain.entities import Administrator, AdminSession


class IdentityRepository(Protocol):
    def single(self) -> Administrator | None: ...
    def by_username(self, username: str) -> Administrator | None: ...
    def administrator(self, identifier) -> Administrator | None: ...
    def add_admin(self, administrator: Administrator) -> None: ...
    def set_password(self, identifier, password_hash: str) -> None: ...
    def session(self, token_hash: str) -> AdminSession | None: ...
    def add_session(self, session: AdminSession) -> None: ...
    def touch(self, identifier, now) -> None: ...
    def revoke(self, identifier, now) -> None: ...
    def revoke_all(self, admin_id, now) -> None: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password_hash: str, password: str) -> bool: ...
