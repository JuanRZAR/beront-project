from typing import Protocol
from uuid import UUID


class OrderRepository(Protocol):
    def lock_operation(self, operation_id: UUID) -> None: ...
    def get(self, identifier: UUID, *, lock=False) -> dict: ...
    def by_operation(self, operation_id: UUID) -> dict | None: ...
    def by_code(self, code_hash: str) -> dict: ...
    def add(self, data: dict) -> None: ...
    def save(self, data: dict) -> dict: ...
    def history(self, order_id: UUID, status: dict, actor_id: UUID | None) -> None: ...
    def receipt(self, order_id: UUID, asset_id: UUID, actor_id: UUID | None) -> None: ...
    def status(self, identifier: UUID | None = None, *, purpose=None) -> dict: ...
    def transition(self, start: UUID, end: UUID) -> None: ...
    def listing(self, query: dict) -> dict: ...
    def definitions(self, resource: str) -> list[dict]: ...
    def add_definition(self, resource: str, data: dict) -> dict: ...
    def save_definition(self, resource: str, identifier: UUID, data: dict) -> dict: ...
    def recover(self, cedula: str, ip_hash: str, cooldown_seconds: int) -> dict: ...


class Mailer(Protocol):
    configured: bool

    def send(self, recipient: str, subject: str, body: str) -> None: ...
