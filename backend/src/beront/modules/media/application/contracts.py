from typing import Protocol
from uuid import UUID

from beront.modules.media.domain.entities import MediaAsset


class MediaRepository(Protocol):
    def asset(self, identifier: UUID) -> MediaAsset: ...
    def register(self, data: dict) -> tuple[MediaAsset, bool]: ...
    def listing(self, q: str, page: int, page_size: int) -> tuple[list[MediaAsset], int]: ...
    def update(self, identifier: UUID, data: dict) -> MediaAsset: ...
    def delete(self, identifier: UUID, version: int) -> MediaAsset: ...
    def visible(self, filename: str, *, private=False) -> MediaAsset: ...
